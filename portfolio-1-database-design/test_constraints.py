"""
Negative tests: every business rule in schema.sql must REJECT bad data.

    python portfolio-1-database-design/test_constraints.py

Each case runs inside a transaction that is always rolled back, so the dataset is untouched.
Output: constraint_tests.md
"""
import sys
from pathlib import Path

import psycopg

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from db import PG_DSN  # noqa: E402

CASES = [
    ("BVN must be 11 digits", "CHECK",
     "INSERT INTO customer(bvn,first_name,last_name,email,phone,date_of_birth,state_code,home_branch_id) "
     "VALUES ('123','A','B','a@b.ng','+2348099999999','1990-01-01','LA',1)"),
    ("Duplicate BVN", "UNIQUE",
     "INSERT INTO customer(bvn,first_name,last_name,email,phone,date_of_birth,state_code,home_branch_id) "
     "SELECT bvn,'A','B','new@b.ng','+2348099999999','1990-01-01','LA',1 FROM customer WHERE customer_id=2"),
    ("Customer must be 18+", "CHECK",
     "INSERT INTO customer(bvn,first_name,last_name,email,phone,date_of_birth,state_code,home_branch_id) "
     "VALUES ('99999999999','A','B','kid@b.ng','+2348099999999',current_date - 3650,'LA',1)"),
    ("Unknown state (FK)", "FOREIGN KEY",
     "INSERT INTO customer(bvn,first_name,last_name,email,phone,date_of_birth,state_code,home_branch_id) "
     "VALUES ('99999999999','A','B','x@b.ng','+2348099999999','1990-01-01','ZZ',1)"),
    ("Savings account cannot overdraw", "CHECK",
     "UPDATE account SET balance = -1 WHERE account_type='SAVINGS' AND account_id = (SELECT min(account_id) FROM account WHERE account_type='SAVINGS')"),
    ("Overdraft only on CURRENT accounts", "CHECK",
     "UPDATE account SET overdraft_limit = 1000 WHERE account_id = (SELECT min(account_id) FROM account WHERE account_type='WALLET')"),
    ("CLOSED account needs closed_at", "CHECK",
     "UPDATE account SET status='CLOSED' WHERE account_id = 3"),
    ("Transaction amount must be positive", "CHECK",
     "INSERT INTO txn(txn_type,channel,amount) VALUES ('TRANSFER','WEB',-50)"),
    ("REVERSAL must reference a txn", "CHECK",
     "INSERT INTO txn(txn_type,channel,amount) VALUES ('REVERSAL','WEB',50)"),
    ("A txn can be reversed only once", "UNIQUE",
     "INSERT INTO txn(txn_type,channel,amount,status,completed_at,reverses_txn_id) "
     "SELECT 'REVERSAL','WEB',amount,'COMPLETED',now(),reverses_txn_id FROM txn WHERE reverses_txn_id IS NOT NULL LIMIT 1"),
    ("FAILED txn needs a reason", "CHECK",
     "INSERT INTO txn(txn_type,channel,amount,status) VALUES ('TRANSFER','WEB',50,'FAILED')"),
    ("Ledger is append-only (UPDATE)", "TRIGGER",
     "UPDATE ledger_entry SET amount = 1 WHERE entry_id = 1"),
    ("Ledger is append-only (DELETE)", "TRIGGER",
     "DELETE FROM ledger_entry WHERE entry_id = 1"),
    ("Unbalanced posting rejected at COMMIT", "DEFERRED TRIGGER",
     "WITH t AS (INSERT INTO txn(txn_type,channel,amount,status,completed_at) VALUES ('TRANSFER','WEB',10,'COMPLETED',now()) RETURNING txn_id) "
     "INSERT INTO ledger_entry(txn_id,account_id,direction,amount,balance_after) SELECT txn_id,3,'D',10,0 FROM t; "
     "SET CONSTRAINTS ALL IMMEDIATE"),
    ("transfer_funds rejects insufficient funds", "PROCEDURE",
     "CALL transfer_funds('{poor}', '{rich2}', 999999999)"),
]

POSITIVE = ("Valid transfer through transfer_funds (then rolled back)",
            "CALL transfer_funds('{rich1}', '{rich2}', 5000)")


def main():
    rows = []
    with psycopg.connect(PG_DSN) as c:
        acc = [r[0] for r in c.execute("""SELECT account_number FROM bank.account WHERE status='ACTIVE' AND account_id>2
                                          ORDER BY balance DESC LIMIT 2""")]
        poor = c.execute("SELECT account_number FROM bank.account WHERE account_type='SAVINGS' AND status='ACTIVE' "
                         "ORDER BY balance LIMIT 1").fetchone()[0]
        names = {"rich1": acc[0], "rich2": acc[1], "poor": poor}
        c.rollback()
        for name, kind, sql in CASES:
            sql = sql.format(**names)
            try:
                c.execute("SET search_path = bank, public")
                c.execute(sql)
                rows.append((name, kind, "ACCEPTED (BUG)", ""))
            except psycopg.Error as e:
                rows.append((name, kind, "rejected", f"{e.sqlstate}: {e.diag.message_primary}"))
            c.rollback()
        c.execute("SET search_path = bank, public")
        c.execute(POSITIVE[1].format(**names))
        n = c.execute("SELECT count(*) FROM audit_log").fetchone()[0]
        rows.append((POSITIVE[0], "PROCEDURE", "accepted", f"audit_log rows written by trigger: {n}"))
        c.rollback()
    md = ["# Constraint tests", "", "Generated by `test_constraints.py`; every case is rolled back.", "",
          "| # | Rule | Mechanism | Result | Database message |", "|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        md.append(f"| {i} | {r[0]} | {r[1]} | **{r[2]}** | `{r[3].replace('|', '/')}` |")
    ok = all(r[2] == "rejected" for r in rows[:-1]) and rows[-1][2] == "accepted"
    md += ["", f"**{sum(r[2] == 'rejected' for r in rows)}/{len(CASES)} invalid operations rejected; "
               f"valid transfer accepted. {'ALL PASS' if ok else 'FAILURES PRESENT'}**"]
    out = Path(__file__).with_name("constraint_tests.md")
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
